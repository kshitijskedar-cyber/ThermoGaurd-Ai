import { useMemo } from "react";
import { Link } from "react-router-dom";
import DataGate from "@/components/common/DataGate";
import StatusDot from "@/components/common/StatusDot";
import { PersistenceChip, RiskStatusBadge } from "@/components/common/Chips";
import BarList, { type BarItem, type BarTone } from "@/components/Charts/BarList";
import TimelinePanel from "@/components/Charts/TimelinePanel";
import { Panel } from "@/components/Investigation/parts";
import { useAlerts } from "@/hooks/useAlerts";
import { useFacilityStats } from "@/hooks/useFacilityStats";
import { useThermalData } from "@/hooks/useThermalData";
import { buildInsights, classificationGroups, industrialCorrelation, persistentHotspots, riskDistribution } from "@/services/intelligence/analytics";
import { PROXIMITY_RANGE_KM } from "@/services/analysis/engine";
import { RELATED_RADIUS_KM, ZONE_KM } from "@/services/intelligence/facilities";
import { CLASS_LABEL, RISK_LABEL, formatShortIST } from "@/utils/format";
import { DataTag } from "@/components/common/SourceTag";

const GROUP_TONE: Record<string, BarTone> = { industrial_fire: "high", persistent: "blue", controlled: "steel", non_industrial: "slate" };

function Analytics() {
  const { dataset, assessments, source } = useThermalData();
  const { summary } = useAlerts();
  const stats = useFacilityStats();

  const view = useMemo(() => {
    if (!dataset) return null;
    const hotspots = persistentHotspots(stats);
    const total = dataset.events.length;
    const pct = (n: number) => (total ? Math.round((n / total) * 100) : 0);
    const risk: BarItem[] = riskDistribution(dataset).map((b) => ({ key: b.level, label: RISK_LABEL[b.level], value: b.count, share: b.share, tone: b.level, to: `/alerts?risk=${b.level}` }));
    const classes: BarItem[] = classificationGroups(dataset).map((g) => ({
      key: g.def.key, label: g.def.label, value: g.count, share: g.share, tone: GROUP_TONE[g.def.key], hint: g.def.hint,
      parts: g.parts.map((p) => ({ key: p.cls, label: CLASS_LABEL[p.cls], value: p.count, to: `/alerts?cls=${p.cls}` })),
    }));
    const c = industrialCorrelation(dataset, assessments);
    const corr: BarItem[] = [
      { key: "near", label: "Near industrial facilities", value: c.near, share: pct(c.near), tone: "high", hint: `Within ${ZONE_KM} km of a facility` },
      { key: "mid", label: "Moderately close", value: c.moderate, share: pct(c.moderate), tone: "moderate", hint: `${ZONE_KM}–${PROXIMITY_RANGE_KM} km from the nearest facility` },
      { key: "far", label: "Far from industrial facilities", value: c.far, share: pct(c.far), tone: "slate", hint: `More than ${PROXIMITY_RANGE_KM} km from the nearest facility` },
    ];
    return { hotspots, risk, classes, corr, total, insights: buildInsights(dataset, assessments, hotspots, summary) };
  }, [dataset, assessments, stats, summary]);

  if (!dataset || !view) return null;
  return (
    <div className="inv analytics-page">
      <Panel eyebrow={source.isLive ? "AI-ASSISTED INSIGHTS · LIVE FIRMS DATA" : "AI-ASSISTED INSIGHTS"} title="Key Insights" aside={<DataTag />}>
        <ul className="insights">
          {view.insights.map((i) => (
            <li key={i.key}>
              <StatusDot tone={i.tone} />
              {i.to ? <Link to={i.to}>{i.text}</Link> : <span>{i.text}</span>}
            </li>
          ))}
        </ul>
        <p className="inv-foot">{source.isLive ? "These statements are calculated from the currently loaded NASA FIRMS observations and OpenStreetMap context using fixed rules. They are not generated by a trained machine-learning model, and a thermal anomaly is not a confirmed fire." : "These statements are calculated from the loaded demonstration dataset using fixed rules. They are not generated by a trained machine-learning model, and the dataset is simulated."}</p>
      </Panel>

      <TimelinePanel ds={dataset} eyebrow="THERMAL ACTIVITY" title="Thermal Events Over Time" subject="a simulated activity history" />

      <div className="an-three">
        <Panel eyebrow="RISK DISTRIBUTION" title="Events by Risk Level" aside={<span className="mono ctx-dist">{view.total} events</span>}>
          <BarList items={view.risk} ariaLabel="Events by risk level" />
          <p className="inv-foot">Counted from each event's Phase 2 risk level. Select a level to open those alerts.</p>
        </Panel>
        <Panel eyebrow="CLASSIFICATION DISTRIBUTION" title="Events by Classification" aside={<span className="mono ctx-dist">{view.total} events</span>}>
          <BarList items={view.classes} ariaLabel="Events by classification group" />
          <p className="inv-foot">The engine's seven classes are reported in four categories; the classes inside each are listed under its bar.</p>
        </Panel>
        <Panel eyebrow="INDUSTRIAL CORRELATION" title="Distance to Industrial Facilities" aside={<span className="mono ctx-dist">{view.total} events</span>}>
          <BarList items={view.corr} ariaLabel="Events by distance to the nearest industrial facility" />
          <p className="inv-foot">Distance to the nearest facility in the dataset{source.isLive ? " (OpenStreetMap objects" + (dataset.sources?.facilities === "OpenStreetMap" ? ")" : " unavailable, so every event counts as far)") : ""}, measured with the same haversine calculation the investigation uses.</p>
        </Panel>
      </div>

      <Panel id="hotspots" eyebrow="PERSISTENT HOTSPOTS" title="Facilities With Repeated Thermal Events" aside={<DataTag />}>
        {view.hotspots.length === 0
          ? <p className="inv-note">No facility has two or more related thermal events in the loaded dataset.</p>
          : <>
              <div className="hot-head" aria-hidden="true"><span>FACILITY</span><span>RELATED EVENTS</span><span>HIGHEST RISK</span><span>PERSISTENCE</span><span>LATEST EVENT</span></div>
              <ul className="hot-list">
                {view.hotspots.map((s) => (
                  <li key={s.facility.id}>
                    <Link className="hot-row" to={`/sites/${s.facility.id}`} aria-label={`Open facility intelligence for ${s.facility.name}`}>
                      <span className="hc hc-name" data-label="FACILITY"><b>{s.facility.name}</b><small>{s.facility.type} · {s.facility.region}</small></span>
                      <span className="hc" data-label="RELATED EVENTS"><b className="mono">{s.total}</b><small>{s.openCount} open</small></span>
                      <span className="hc" data-label="HIGHEST RISK">{s.highest ? <><RiskStatusBadge status={s.highest.level} /><small className="mono">score {s.highest.score}</small></> : "—"}</span>
                      <span className="hc" data-label="PERSISTENCE"><PersistenceChip keyName={s.persistence} label={s.persistenceLabel} /><small className="mono">{s.persistentCount} of {s.total} persistent</small></span>
                      <span className="hc" data-label="LATEST EVENT">{s.lastEvent ? <><span className="mono">{formatShortIST(s.lastEvent.detectedAt)}</span><small className="mono">{s.lastEvent.id}</small></> : "—"}</span>
                    </Link>
                  </li>
                ))}
              </ul>
            </>}
        <p className="inv-foot">A hotspot is a facility with two or more thermal events whose nearest facility it is, within {RELATED_RADIUS_KM} km. {source.isLive ? "Persistent events were detected on at least 60% of the days in the FIRMS window." : "Persistent events were detected on at least 6 of 10 observation days."} Select a row to open Facility Intelligence.</p>
      </Panel>
    </div>
  );
}

export default function AnalyticsPage() { return <DataGate><Analytics /></DataGate>; }
